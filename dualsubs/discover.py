"""Pair loose subtitle files with the video they belong to.

Two naming conventions dominate:

  episodic   S01E01--0001.srt          ->  S01E01--0001-Some Title.mkv
             (the subtitle name is a prefix of the video name)

  movie      Some.Movie.2019.chi.srt   ->  Some.Movie.2019.1080p.BluRay.x264.mkv
             (same title + year, different release metadata)

Both are scored, and a trailing language token in the filename is respected:
a file ending `.eng.srt` will never be handed to the Chinese side. Files with
no language token at all are treated as neutral and may fill either side.

A subtitle only ever belongs to one episode. Loose prefix matching is happy to
pair `Show - S01E01 - Pilot` with `Show - S01E02 - Ep.chi.srt`, since the two
share most of their name, so two guards sit on top of the score: different
episode markers never match, and a file that matches a *sibling* video better
is left for that sibling.

Some releases put subtitles in a folder named after the video, with names that
say nothing but the language (`Subs/<episode>/2_English.srt`). Everything in
such a folder belongs to that video.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass
from pathlib import Path

from . import langs

SUBTITLE_EXTS = (".srt", ".ass", ".ssa", ".vtt", ".sub")

#: Containers a sibling video can be in. Broader than what we process, since
#: a subtitle that belongs to a neighbouring .mp4 still is not ours.
VIDEO_EXTS = (".mkv", ".mp4", ".m4v", ".avi", ".mov", ".webm", ".ts", ".m2ts",
              ".wmv", ".flv", ".mpg", ".mpeg")

#: Sibling folders worth searching, in addition to the video's own folder.
SUBTITLE_DIRS = ("subs", "subtitles", "sub", "subtitle")

#: Written into the header of every script this program generates, so a
#: re-run never mistakes its own output for a source.
GENERATED_MARKER = b"Generated by dual_subs"

#: SxxEyy and 1x02 forms; the bare " - 06 - " form is handled separately.
EPISODE_RES = (
    re.compile(r"\bs(\d{1,2})\s*e(\d{1,3})", re.I),
    re.compile(r"\b(\d{1,2})x(\d{1,3})\b", re.I),
)
BARE_EPISODE_RE = re.compile(r"\s-\s(\d{1,3})(?:\s-\s|$)")

#: Filename tokens that mark a partial subtitle: a forced or signs file
#: carries a handful of cues, not the dialogue.
PARTIAL_TOKENS = frozenset({"forced", "signs", "songs"})
#: Full dialogue, but with sound descriptions; fine, just not first choice.
SDH_TOKENS = frozenset({"sdh", "hi", "cc"})

#: Tokens that mark the end of a movie *title* — release metadata starts here.
RELEASE_TOKENS = frozenset({
    "bluray", "blu", "bdrip", "brrip", "bdremux", "remux", "webrip", "webdl",
    "web", "hdtv", "dvdrip", "hdrip", "uhd", "hddvd", "x264", "x265", "h264",
    "h265", "hevc", "avc", "av1", "xvid", "divx", "10bit", "8bit", "hdr",
    "dv", "sdr", "aac", "ac3", "eac3", "dts", "ddp", "dd", "atmos", "truehd",
    "flac", "opus", "2audio", "2ch", "5", "7", "dual", "yts", "yify", "mx",
    "rarbg", "fgt", "evo", "proper", "repack", "extended", "unrated",
    "remastered", "imax", "internal", "limited",
})


@dataclass
class Candidate:
    path: Path
    score: int
    language: str | None      # canonical code from the filename, if any
    neutral: bool             # no language token at all


def _tokens(name: str) -> list[str]:
    return [t for t in re.split(r"[.\-_ ()\[\]]+", name.lower()) if t]


def _is_resolution(t: str) -> bool:
    return bool(re.fullmatch(r"\d{3,4}[pi]", t))


def _is_year(t: str) -> bool:
    return bool(re.fullmatch(r"(19|20)\d{2}", t))


def movie_signature(name: str) -> tuple[str, str | None]:
    """(title, year): the leading tokens before any release/language/year token."""
    title: list[str] = []
    year: str | None = None
    for index, t in enumerate(_tokens(name)):
        if _is_year(t):
            year = t
            break
        # Never end the title on its own first token: a title that starts
        # with something language-shaped ("Ne Zha", "La La Land") would
        # otherwise reduce to nothing.
        if index and (t in RELEASE_TOKENS or _is_resolution(t)
                      or t in langs.FILENAME_TOKENS):
            break
        title.append(t)
    if year is None:
        for t in _tokens(name):
            if _is_year(t):
                year = t
                break
    return " ".join(title), year


def trailing_language(name: str) -> str | None:
    """The last language-looking token in a filename, e.g. 'Movie.2019.chs'."""
    for t in reversed(_tokens(name)):
        if t in langs.QUALIFIERS:
            continue
        if t in langs.FILENAME_TOKENS:
            return langs.normalize(t)
        if _is_year(t) or _is_resolution(t) or t in RELEASE_TOKENS:
            continue
        break          # a non-language trailing token: stop looking
    return None


def episode_of(name: str) -> tuple[int | None, int] | None:
    """(season, episode) from a filename, or None if it names no episode."""
    for pattern in EPISODE_RES:
        m = pattern.search(name)
        if m:
            return int(m.group(1)), int(m.group(2))
    m = BARE_EPISODE_RE.search(name)
    if m:
        return None, int(m.group(1))
    return None


def _different_episode(a: str, b: str) -> bool:
    ea, eb = episode_of(a), episode_of(b)
    if ea is None or eb is None:
        return False
    if ea[0] is not None and eb[0] is not None and ea[0] != eb[0]:
        return True
    return ea[1] != eb[1]


def _subdirs(folder: Path, wanted: set[str]) -> list[Path]:
    """Children of `folder` whose lowercased name is in `wanted`.

    Matched case-insensitively: NTFS does not care about case but ext4 does,
    and release folders are inconsistent about it ("Subs", "subs", "SUBS").
    """
    try:
        return [e for e in sorted(folder.iterdir())
                if e.is_dir() and e.name.lower() in wanted]
    except OSError:
        return []


def search_dirs(video: Path) -> list[Path]:
    """The video's own folder, plus any `Subs/`-style sibling."""
    return [folder for folder, _ in _search_dirs(video)]


def _search_dirs(video: Path) -> list[tuple[Path, bool]]:
    """(folder, owned) pairs. An owned folder is named after the video, so
    everything in it belongs to this video whatever the files are called."""
    stem = video.stem.lower()
    out: list[tuple[Path, bool]] = [(video.parent, False)]
    for sub in _subdirs(video.parent, set(SUBTITLE_DIRS) | {stem}):
        owned = sub.name.lower() == stem
        out.append((sub, owned))
        if not owned:
            # Subs/<video name>/2_English.srt
            out += [(d, True) for d in _subdirs(sub, {stem})]
    return out


def _sibling_videos(video: Path) -> list[Path]:
    """Other videos in the same folder, which may have a better claim."""
    try:
        names = os.listdir(video.parent)
    except OSError:
        return []
    me = video.name.lower()
    return [video.parent / n for n in names
            if n.lower().endswith(VIDEO_EXTS) and n.lower() != me]


def is_generated(path: Path) -> bool:
    """True for a script this program wrote, which must never be an input."""
    if path.suffix.lower() not in (".ass", ".ssa"):
        return False
    try:
        with open(path, "rb") as fh:
            return GENERATED_MARKER in fh.read(512)
    except OSError:
        return False


def _common_prefix_len(a: str, b: str) -> int:
    n = 0
    for x, y in zip(a, b):
        if x != y:
            break
        n += 1
    return n


def find_candidates(video: Path, exclude: set[Path] | None = None,
                    include_generated: bool = False) -> list[Candidate]:
    """All subtitle files that plausibly belong to `video`, best first.

    `include_generated` keeps this program's own output in the list, which
    renaming needs (the sidecar has to follow its video) and nothing else does.
    """
    exclude_n = {os.path.normcase(os.path.abspath(p)) for p in (exclude or set())}
    video_name = video.stem.lower()
    v_title, v_year = movie_signature(video.stem)
    siblings = [(s.stem.lower(), *movie_signature(s.stem))
                for s in _sibling_videos(video)]

    out: list[Candidate] = []
    seen: set[str] = set()
    for folder, owned in _search_dirs(video):
        try:
            entries = sorted(os.listdir(folder))
        except OSError:
            continue
        in_subs_dir = folder != video.parent
        for fn in entries:
            if not fn.lower().endswith(SUBTITLE_EXTS):
                continue
            path = (folder / fn).resolve()
            key = os.path.normcase(str(path))
            if key in exclude_n or key in seen:
                continue
            seen.add(key)

            base = os.path.splitext(fn)[0].lower()
            if owned:
                score = 800
            else:
                score = _score(video_name, base, v_title, v_year)
                if score is None and in_subs_dir and not siblings:
                    score = 500       # the folder's only video: Subs/ is its
                if score is None:
                    continue
                if any((_score(name, base, title, year) or 0) > score
                       for name, title, year in siblings):
                    continue          # a neighbouring video has the better claim
            if not include_generated and is_generated(path):
                continue
            score += _qualifier_adjustment(video_name, base)
            lang = trailing_language(base)
            out.append(Candidate(path=path, score=score, language=lang,
                                 neutral=lang is None))

    out.sort(key=lambda c: c.score, reverse=True)
    return out


def _qualifier_adjustment(video_name: str, sub_base: str) -> int:
    """Rank `.eng.forced.srt` below `.eng.srt`, which otherwise tie.

    Only words the video's own name does not contain count, so a film called
    "Forced Entry" does not penalise every subtitle it has.
    """
    extra = set(_tokens(sub_base)) - set(_tokens(video_name))
    if extra & PARTIAL_TOKENS:
        return -300
    if extra & SDH_TOKENS:
        return -30
    return 0


def _score(video_name: str, sub_base: str,
           v_title: str, v_year: str | None) -> int | None:
    if video_name == sub_base:
        return 1000
    if _different_episode(video_name, sub_base):
        return None
    if video_name.startswith(sub_base):
        return 700 + len(sub_base)                       # episodic prefix match
    if sub_base.startswith(video_name):
        return 690 + len(video_name)                     # video name + .chs suffix
    s_title, s_year = movie_signature(sub_base)
    if v_title and s_title and v_title == s_title and (
        not v_year or not s_year or v_year == s_year
    ):
        return 600 + (50 if v_year and v_year == s_year else 0)
    cp = _common_prefix_len(video_name, sub_base)
    if cp >= max(5, int(0.6 * min(len(video_name), len(sub_base) or 1))):
        return 100 + cp
    return None


def pick(video: Path, language: str, exclude: set[Path] | None = None
         ) -> Candidate | None:
    """Best subtitle file for one language side, or None."""
    cands = find_candidates(video, exclude)
    if not cands:
        return None
    wanted = langs.normalize(language)
    exact = [c for c in cands if c.language == wanted]
    if exact:
        return exact[0]
    neutral = [c for c in cands if c.neutral]
    if neutral:
        return neutral[0]
    return None    # everything left is explicitly a *different* language
