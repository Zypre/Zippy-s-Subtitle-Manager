"""Build the merged dual-language ASS script."""

from __future__ import annotations

import math
import re
import unicodedata
from dataclasses import dataclass, field

from .formats import Event

TOP_STYLE = "TopLang"
BOT_STYLE = "BottomLang"


@dataclass
class SideStyle:
    """Appearance of one of the two subtitle lines."""

    font: str = "Arial"
    size: int = 52
    margin_v: int = 100
    spacing: int = 0
    scale_x: int = 100
    scale_y: int = 100
    bold: bool = False
    italic: bool = False
    primary: str = "&H00FFFFFF"     # ASS colours are &HAABBGGRR
    outline_colour: str = "&H00000000"
    back_colour: str = "&H64000000"
    outline: float = 2
    shadow: float = 1
    border_style: int = 1           # 1 = outline+shadow, 3 = opaque box

    def to_style_line(self, name: str) -> str:
        # A comma would end the field early and shift every value after it.
        font = self.font.replace(",", " ").strip() or "Arial"
        return (
            f"Style: {name},{font},{self.size},{self.primary},&H000000FF,"
            f"{self.outline_colour},{self.back_colour},"
            f"{-1 if self.bold else 0},{-1 if self.italic else 0},0,0,"
            f"{self.scale_x},{self.scale_y},{self.spacing},0,"
            f"{self.border_style},{self.outline},{self.shadow},2,10,10,{self.margin_v},1"
        )


@dataclass
class Layout:
    play_res_x: int = 1920
    play_res_y: int = 1080
    #: Lift the top line by one bottom-line-height for each extra line in an
    #: overlapping bottom cue, so a two-line bottom sub never collides.
    auto_lift: bool = True
    line_height_factor: float = 1.2


#: Horizontal room a line gets before the renderer wraps it: the canvas less
#: the style's 10 px left and right margins.
SIDE_MARGINS = 20

#: Average advance of a narrow (Latin, Cyrillic...) glyph, in ems. Arial's
#: mixed-case average with spaces sits a little under this; erring wide means
#: an occasional unnecessary lift, never an overlap.
NARROW_EM = 0.5

_TAGS_RE = re.compile(r"\{[^}]*\}")

_HEADER = """\
[Script Info]
; Generated by dual_subs
ScriptType: v4.00+
WrapStyle: 0
PlayResX: {play_x}
PlayResY: {play_y}
ScaledBorderAndShadow: yes
YCbCr Matrix: None

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
{top_style}
{bot_style}

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"""


def build_ass(
    top_events: list[Event],
    bot_events: list[Event],
    top: SideStyle,
    bot: SideStyle,
    layout: Layout | None = None,
) -> str:
    """Return the full text of a merged ASS script."""
    layout = layout or Layout()
    header = _HEADER.format(
        play_x=layout.play_res_x,
        play_y=layout.play_res_y,
        top_style=top.to_style_line(TOP_STYLE),
        bot_style=bot.to_style_line(BOT_STYLE),
    )

    lines = [header, ""]
    if layout.auto_lift:
        top_events, bot_events = _position(top_events, bot_events, top, bot, layout)

    # Interleave by start time so the file reads sensibly; libass does not care.
    for ev, style in sorted(
        [(e, TOP_STYLE) for e in top_events] + [(e, BOT_STYLE) for e in bot_events],
        key=lambda pair: (pair[0].start, pair[0].end),
    ):
        lines.append(ev.to_dialogue(style))
    return "\n".join(lines) + "\n"


def _position(
    top_events: list[Event],
    bot_events: list[Event],
    top: SideStyle,
    bot: SideStyle,
    layout: Layout,
) -> tuple[list[Event], list[Event]]:
    """Pin every cue with \\pos so libass skips collision handling.

    The bottom line sits at its margin. Each top cue is raised by one bottom
    line-height for every *extra* line in whatever bottom cue overlaps it in
    time, so no manual margin tweaking is needed. Cues that already position
    themselves (\\an8 signs, karaoke) are left exactly as authored.
    """
    cx = layout.play_res_x // 2
    line_h = int(round(bot.size * layout.line_height_factor))
    y_top_base = layout.play_res_y - top.margin_v
    y_bot = layout.play_res_y - bot.margin_v

    spans = [
        (e.start, e.end, visual_lines(e, bot, layout))
        for e in bot_events
        if not e.has_positional_override
    ]

    def place_top(ev: Event) -> Event:
        if ev.has_positional_override:
            return ev
        overlap_lines = 1
        for b_start, b_end, b_lines in spans:
            if b_start < ev.end and ev.start < b_end and b_lines > overlap_lines:
                overlap_lines = b_lines
        y = y_top_base - (overlap_lines - 1) * line_h
        return _with_pos(ev, cx, y)

    def place_bot(ev: Event) -> Event:
        return ev if ev.has_positional_override else _with_pos(ev, cx, y_bot)

    return [place_top(e) for e in top_events], [place_bot(e) for e in bot_events]


def visual_lines(ev: Event, style: SideStyle, layout: Layout) -> int:
    """How many lines a cue will occupy on screen, wrapping included.

    Counting `\\N` alone misses the commonest case: one long line that the
    renderer wraps by itself. The width is estimated, not measured -- a
    full-width (CJK) glyph is one em, anything else about half -- which is
    close enough to know whether a line fits.
    """
    avail = max(1, layout.play_res_x - SIDE_MARGINS)
    em = style.size * style.scale_x / 100
    total = 0
    for segment in _TAGS_RE.sub("", ev.text).replace(r"\h", " ").split(r"\N"):
        width = 0.0
        for ch in segment:
            wide = unicodedata.east_asian_width(ch) in ("W", "F")
            width += em * (1.0 if wide else NARROW_EM) + style.spacing
        total += max(1, math.ceil(width / avail))
    return total


def _with_pos(ev: Event, x: int, y: int) -> Event:
    from dataclasses import replace
    return replace(ev, text=f"{{\\pos({x},{y})}}" + ev.text)
